#!/usr/bin/env node

const fs = require('fs');
const http = require('http');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const catalogPath = path.join(repoRoot, 'examples', 'catalog.json');
const defaultDocPath = path.join(repoRoot, 'docs', 'examples-static-quality-audit.md');

const args = process.argv.slice(2);
const shouldWriteDoc = args.includes('--write-doc');
const failOnIssues = args.includes('--fail-on-issues');
const baseUrlArg = args.find((arg) => arg.startsWith('--base-url='));
const baseUrl = baseUrlArg ? baseUrlArg.split('=').slice(1).join('=').replace(/\/$/, '') : null;

function readText(relativePath) {
  return fs.readFileSync(path.join(repoRoot, relativePath), 'utf8');
}

function exists(relativePath) {
  return !!relativePath && fs.existsSync(path.join(repoRoot, relativePath));
}

function isDirectory(relativePath) {
  return !!relativePath && fs.existsSync(path.join(repoRoot, relativePath)) &&
    fs.statSync(path.join(repoRoot, relativePath)).isDirectory();
}

function normalizeRelative(relativePath) {
  return relativePath.replace(/^\.\//, '').replace(/\\/g, '/');
}

function pagePathFor(entry) {
  if (entry.links?.demo && !/^https?:\/\//.test(entry.links.demo)) {
    return normalizeRelative(entry.links.demo);
  }
  if (!entry.path || /^https?:\/\//.test(entry.path)) return null;
  if (entry.path.endsWith('.html')) return normalizeRelative(entry.path);
  return normalizeRelative(`${entry.path.replace(/\/?$/, '/')}index.html`);
}

function titleOf(html) {
  const match = html.match(/<title[^>]*>([\s\S]*?)<\/title>/i);
  return match ? match[1].replace(/\s+/g, ' ').trim() : '';
}

function headingOf(html) {
  const match = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i);
  return match ? match[1].replace(/<[^>]*>/g, '').replace(/\s+/g, ' ').trim() : '';
}

function isWeakTitle(title) {
  if (!title) return true;
  const normalized = title.toLowerCase().trim();
  return [
    'orphe.js',
    'orphe core js demo',
    'orphe core',
    'document',
    'index',
    'sample',
    'demo',
    'uoo',
  ].includes(normalized);
}

function isPublicEntry(entry) {
  return entry.status === 'public' || entry.status === 'public-candidate';
}

function maybeRead(relativePath) {
  if (!relativePath || !exists(relativePath)) return '';
  return readText(relativePath);
}

function localScriptPaths(html, pagePath) {
  const pageDir = path.posix.dirname(pagePath);
  const scripts = [];
  const scriptRe = /<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi;
  let match;
  while ((match = scriptRe.exec(html))) {
    const src = match[1];
    if (!src || /^https?:\/\//.test(src) || src.startsWith('//')) continue;
    scripts.push(normalizeRelative(path.posix.normalize(path.posix.join(pageDir, src))));
  }
  return scripts;
}

function localScriptText(html, pagePath) {
  return localScriptPaths(html, pagePath)
    .map((scriptPath) => maybeRead(scriptPath))
    .filter(Boolean)
    .join('\n');
}

function httpHead(url) {
  return new Promise((resolve) => {
    const req = http.request(url, { method: 'HEAD', timeout: 2500 }, (res) => {
      res.resume();
      resolve({ ok: res.statusCode >= 200 && res.statusCode < 400, status: res.statusCode });
    });
    req.on('timeout', () => {
      req.destroy();
      resolve({ ok: false, status: 'timeout' });
    });
    req.on('error', (error) => resolve({ ok: false, status: error.code || error.message }));
    req.end();
  });
}

function addIssue(issues, severity, id, message) {
  issues.push({ severity, id, message });
}

function markdownTable(rows, headers) {
  if (!rows.length) return '_None._\n';
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((row) => `| ${headers.map((header) => String(row[header] ?? '').replace(/\n/g, '<br>')).join(' | ')} |`);
  return [head, sep, ...body].join('\n') + '\n';
}

function buildMarkdown(report) {
  const now = new Date().toISOString();
  const issueRows = report.issues.map((issue) => ({
    severity: issue.severity,
    id: issue.id,
    issue: issue.message,
  }));
  const statusRows = Object.entries(report.statusCounts).map(([status, count]) => ({ status, count }));
  const categoryRows = Object.entries(report.categoryCounts).map(([category, count]) => ({ category, count }));
  const candidateRows = report.candidates.map((entry) => ({
    id: entry.id,
    path: entry.path,
    category: entry.category,
    needs: entry.needs_real_device_validation ? 'real-device validation' : '',
  }));
  return `# Examples Static Quality Audit

Generated: ${now}

This audit is generated by \`node scripts/check-examples-static-quality.js --write-doc${baseUrl ? ` --base-url=${baseUrl}` : ''}\`.
It is a static/public-surface check only. It does not claim real-device validation.

## Summary

- Catalog entries: ${report.totalEntries}
- Public entries: ${report.publicCount}
- Public candidates: ${report.candidateCount}
- Errors: ${report.errorCount}
- Warnings: ${report.warningCount}
- Info: ${report.infoCount}

## Status Counts

${markdownTable(statusRows, ['status', 'count'])}

## Category Counts

${markdownTable(categoryRows, ['category', 'count'])}

## Public Candidates

${markdownTable(candidateRows, ['id', 'path', 'category', 'needs'])}

## Findings

${markdownTable(issueRows, ['severity', 'id', 'issue'])}

## Notes

- \`favicon.ico\` 404 is common with the local Python server and is not treated as a blocking issue.
- Web Audio autoplay warnings from p5.sound are expected until a user gesture resumes audio.
- Browser extension messages such as "message channel closed" are not repository issues.
- Real-device validation must still be performed in Chrome for BLE behavior, game input, and gait data correctness.
`;
}

async function main() {
  const catalog = JSON.parse(fs.readFileSync(catalogPath, 'utf8'));
  const entries = catalog.entries || [];
  const issues = [];
  const statusCounts = {};
  const categoryCounts = {};
  const publicEntries = entries.filter(isPublicEntry);
  const candidates = entries.filter((entry) => entry.status === 'public-candidate');
  let localHttpUnavailable = false;

  for (const entry of entries) {
    statusCounts[entry.status] = (statusCounts[entry.status] || 0) + 1;
    categoryCounts[entry.category] = (categoryCounts[entry.category] || 0) + 1;
  }

  for (const entry of publicEntries) {
    const id = entry.id;
    const pagePath = pagePathFor(entry);
    const sourcePath = entry.links?.source || entry.path;
    const sourceIsDir = sourcePath && !/^https?:\/\//.test(sourcePath) && isDirectory(sourcePath);

    if (!entry.path || !exists(entry.path)) {
      addIssue(issues, 'error', id, `catalog path does not exist: ${entry.path}`);
    }

    if (!pagePath || !exists(pagePath)) {
      addIssue(issues, 'error', id, `demo/index page does not exist: ${pagePath || '(none)'}`);
      continue;
    }

    if (baseUrl) {
      const url = `${baseUrl}/${pagePath}`;
      const result = await httpHead(url);
      if (!result.ok && result.status === 'EPERM') {
        localHttpUnavailable = true;
      } else if (!result.ok) {
        addIssue(issues, 'error', id, `HEAD ${url} failed: ${result.status}`);
      }
    }

    const html = maybeRead(pagePath);
    const title = titleOf(html);
    const heading = headingOf(html);
    if (isWeakTitle(title)) addIssue(issues, 'warning', id, `weak or generic <title>: "${title || '(empty)'}" in ${pagePath}`);
    if (/mario/i.test(title) || /mario/i.test(heading) || /mario/i.test(entry.title)) {
      addIssue(issues, 'warning', id, `public-facing title/heading may contain Mario branding: title="${title}", h1="${heading}", catalog="${entry.title}"`);
    }

    if (sourceIsDir && !exists(`${sourcePath.replace(/\/?$/, '/') }README.md`)) {
      addIssue(issues, 'warning', id, `missing README.md in ${sourcePath}`);
    }

    if (!entry.thumbnail) {
      addIssue(issues, 'warning', id, 'missing thumbnail field');
    } else if (!exists(entry.thumbnail)) {
      addIssue(issues, 'error', id, `thumbnail does not exist: ${entry.thumbnail}`);
    }

    if (pagePath.startsWith('examples/') && !html.includes('site-analytics.js')) {
      addIssue(issues, 'warning', id, `${pagePath} does not include site-analytics.js`);
    }

    if (html.includes('CoreToolkit.js')) {
      const scriptText = localScriptText(html, pagePath);
      const combinedText = `${html}\n${scriptText}`;
      if (!html.includes('BleSharedBridge.js')) {
        addIssue(issues, 'error', id, `${pagePath} uses CoreToolkit.js but does not include BleSharedBridge.js`);
      }
      if (!combinedText.includes('guardCoreToolkitBluetooth(')) {
        addIssue(issues, 'warning', id, `${pagePath} uses CoreToolkit.js but does not call guardCoreToolkitBluetooth()`);
      }
    }

    if (/cdn\.jsdelivr\.net\/gh\/Orphe-OSS\/ORPHE-CORE\.js@main\/js\/ORPHE-CORE\.js/.test(html)) {
      addIssue(issues, 'warning', id, `${pagePath} loads ORPHE-CORE.js from @main CDN instead of local source`);
    }

    const legacyNotify = html.match(/['"](RAW|ANALYSIS|ANALYSIS_AND_RAW)['"]/g);
    if (legacyNotify) {
      addIssue(issues, 'warning', id, `${pagePath} contains legacy notification names: ${[...new Set(legacyNotify)].join(', ')}`);
    }
  }

  const candidateDoc = exists('docs/public-candidate-validation.md')
    ? readText('docs/public-candidate-validation.md')
    : '';
  candidates.forEach((entry) => {
    if (!candidateDoc.includes(entry.path) && !candidateDoc.includes(entry.id)) {
      addIssue(issues, 'warning', entry.id, 'public-candidate is missing from docs/public-candidate-validation.md');
    }
  });

  const displayIds = JSON.stringify(maybeRead('examples/gallery.js'));
  publicEntries.forEach((entry) => {
    if (!displayIds.includes(entry.id)) {
      addIssue(issues, 'info', entry.id, 'gallery.js has no Japanese override for this entry');
    }
  });

  if (localHttpUnavailable) {
    addIssue(issues, 'info', 'local-http', 'Node http HEAD checks are unavailable in this sandbox (EPERM). Use curl -I for spot checks.');
  }

  const report = {
    totalEntries: entries.length,
    publicCount: entries.filter((entry) => entry.status === 'public').length,
    candidateCount: candidates.length,
    statusCounts,
    categoryCounts,
    candidates,
    issues,
    errorCount: issues.filter((issue) => issue.severity === 'error').length,
    warningCount: issues.filter((issue) => issue.severity === 'warning').length,
    infoCount: issues.filter((issue) => issue.severity === 'info').length,
  };

  console.log(`Examples static quality: ${report.errorCount} errors, ${report.warningCount} warnings, ${report.infoCount} info`);
  for (const issue of issues) {
    console.log(`${issue.severity.toUpperCase()}: ${issue.id}: ${issue.message}`);
  }

  if (shouldWriteDoc) {
    fs.writeFileSync(defaultDocPath, buildMarkdown(report));
    console.log(`Wrote ${path.relative(repoRoot, defaultDocPath)}`);
  }

  if (failOnIssues && report.errorCount > 0) {
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
